    private static Map<String, Map<String, String>> table;

    private VBVCemNames() {}

    /** @return the vanilla part name for an OptiFine part name of the given model (the name itself when unlisted) */
    static String vanilla(String model, String optifinePart) {
        Map<String, String> renames = renames(model);
        String mapped = renames == null ? null : renames.get(optifinePart);
        return mapped != null ? mapped : optifinePart;
    }

    private static Map<String, String> renames(String model) {
        if (table == null) {
            table = new HashMap<>();
            for (int i = 0; i + 1 < DATA.length; i += 2) {
                Map<String, String> pairs = new HashMap<>();
                for (String pair : DATA[i + 1].split(",")) {
                    int eq = pair.indexOf('=');
                    if (eq > 0) {
                        pairs.put(pair.substring(0, eq), pair.substring(eq + 1));
                    }
                }
                table.put(DATA[i], pairs);
            }
        }
        return table.get(model);
    }
